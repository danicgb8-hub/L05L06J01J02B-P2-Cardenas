TIM_HandleTypeDef tim3;
TIM_OC_InitTypeDef Config_tim3;
GPIO_InitTypeDef GPIO_PWM;
GPIO_InitTypeDef Pin_Pulsador;
/* Private define ------------------------------------------------------------*/
/* Private macro -------------------------------------------------------------*/
/* Private variables ---------------------------------------------------------*/
double Duty_Cycle;
/* Private function prototypes -----------------------------------------------*/
static void SystemClock_Config(void);
static void Error_Handler(void);

/* Private functions ---------------------------------------------------------*/
static void init_TIM3(void){
  TIM_OC_InitTypeDef Config_tim3;
  
  tim3.Instance = TIM3;
  tim3.Init.Period = 21000;     //Ciclos de reloj que tienen que pasar para que la señal vuelva a 0
  tim3.Init.Prescaler = 1;
  tim3.Init.ClockDivision = TIM_CLOCKDIVISION_DIV1;
  tim3.Init.CounterMode = TIM_COUNTERMODE_UP;
  HAL_TIM_PWM_Init(&tim3);
  
  Config_tim3.OCMode = TIM_OCMODE_PWM2;
  Config_tim3.Pulse = Duty_Cycle*tim3.Init.Period;      //Ciclo de trabajo un 25% del periodo
  Config_tim3.OCNPolarity = TIM_OCPOLARITY_HIGH;
  Config_tim3.OCFastMode = TIM_OCFAST_DISABLE;
  HAL_TIM_PWM_ConfigChannel(&tim3, &Config_tim3, TIM_CHANNEL_1);
}

static void GPIO_Init(GPIO_InitTypeDef *gpio){
  
  gpio->Pin = GPIO_PIN_4;
  gpio->Mode = GPIO_MODE_AF_PP;
  gpio->Alternate = GPIO_AF2_TIM3;
  gpio->Pull = GPIO_NOPULL;
  gpio->Speed = GPIO_SPEED_FREQ_LOW;    //Señal es de 2KHz, suficientemente baja
  
  HAL_GPIO_Init(GPIOB, gpio);

}

/* INTERRUPCION PULSADOR */
void EXTI15_10_IRQHandler(void){
  HAL_GPIO_EXTI_IRQHandler(GPIO_PIN_13);
}

void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin){
  if(GPIO_Pin == GPIO_PIN_13){
      if(Duty_Cycle < 0.80){
        Duty_Cycle += 0.20;
        __HAL_TIM_SET_COMPARE(&tim3, TIM_CHANNEL_1, Duty_Cycle*tim3.Init.Period);
      }
  }
}
/**
  * @brief  Main program
  * @param  None
  * @retval None
  */
int main(void)
{

  /* STM32F4xx HAL library initialization:
       - Configure the Flash prefetch, Flash preread and Buffer caches
       - Systick timer is configured by default as source of time base, but user 
             can eventually implement his proper time base source (a general purpose 
             timer for example or other time source), keeping in mind that Time base 
             duration should be kept 1ms since PPP_TIMEOUT_VALUEs are defined and 
             handled in milliseconds basis.
       - Low Level Initialization
     */
  HAL_Init();

  /* Configure the system clock to 168 MHz */
  SystemClock_Config();
  SystemCoreClockUpdate();

  /* Add your application code here*/
  Duty_Cycle = 0.20;
  
  __HAL_RCC_TIM3_CLK_ENABLE();
  init_TIM3();
  HAL_TIM_PWM_Start(&tim3, TIM_CHANNEL_1);
  
  __HAL_RCC_GPIOB_CLK_ENABLE();
  GPIO_Init(&GPIO_PWM);
  
  /* Confiracion Pulsacion */
  HAL_NVIC_EnableIRQ(EXTI15_10_IRQn);
  
  __HAL_RCC_GPIOC_CLK_ENABLE();             //Habilitamos reloj del puerto donde esta el pulsador
  
  Pin_Pulsador.Mode = GPIO_MODE_IT_RISING;
  Pin_Pulsador.Pin = GPIO_PIN_13;
  Pin_Pulsador.Pull = GPIO_PULLDOWN;
  HAL_GPIO_Init(GPIOC, &Pin_Pulsador);
  
#ifdef RTE_CMSIS_RTOS2
  /* Initialize CMSIS-RTOS2 */
  osKernelInitialize ();

  /* Create thread functions that start executing, 
  Example: osThreadNew(app_main, NULL, NULL); */

  /* Start thread execution */
  osKernelStart();
#endif

  /* Infinite loop */
  while (1)
  {
  }
}

/**
  * @brief  System Clock Configuration
  *         The system Clock is configured as follow : 
  *            System Clock source            = PLL (HSE)
  *            SYSCLK(Hz)                     = 168000000
  *            HCLK(Hz)                       = 168000000
  *            AHB Prescaler                  = 1
  *            APB1 Prescaler                 = 4
  *            APB2 Prescaler                 = 2
  *            HSE Frequency(Hz)              = 8000000
  *            PLL_M                          = 25
  *            PLL_N                          = 336
  *            PLL_P                          = 2
  *            PLL_Q                          = 7
  *            VDD(V)                         = 3.3
  *            Main regulator output voltage  = Scale1 mode
  *            Flash Latency(WS)              = 5
  * @param  None
  * @retval None
  */
static void SystemClock_Config(void)
{
  RCC_ClkInitTypeDef RCC_ClkInitStruct;
  RCC_OscInitTypeDef RCC_OscInitStruct;

  /* Enable Power Control clock */
  __HAL_RCC_PWR_CLK_ENABLE();

  /* The voltage scaling allows optimizing the power consumption when the device is 
     clocked below the maximum system frequency, to update the voltage scaling value 
     regarding system frequency refer to product datasheet.  */
  __HAL_PWR_VOLTAGESCALING_CONFIG(PWR_REGULATOR_VOLTAGE_SCALE1);

  /* Enable HSE Oscillator and activate PLL with HSE as source */
  RCC_OscInitStruct.OscillatorType = RCC_OSCILLATORTYPE_HSE;
  RCC_OscInitStruct.HSEState = RCC_HSE_ON;
  RCC_OscInitStruct.PLL.PLLState = RCC_PLL_ON;
  RCC_OscInitStruct.PLL.PLLSource = RCC_PLLSOURCE_HSE;
  RCC_OscInitStruct.PLL.PLLM = 8;
  RCC_OscInitStruct.PLL.PLLN = 336;
  RCC_OscInitStruct.PLL.PLLP = RCC_PLLP_DIV2;
  RCC_OscInitStruct.PLL.PLLQ = 7;
  if(HAL_RCC_OscConfig(&RCC_OscInitStruct) != HAL_OK)
  {
    /* Initialization Error */
    Error_Handler();
  }

  /* Select PLL as system clock source and configure the HCLK, PCLK1 and PCLK2 
     clocks dividers */
  RCC_ClkInitStruct.ClockType = (RCC_CLOCKTYPE_SYSCLK | RCC_CLOCKTYPE_HCLK | RCC_CLOCKTYPE_PCLK1 | RCC_CLOCKTYPE_PCLK2);
  RCC_ClkInitStruct.SYSCLKSource = RCC_SYSCLKSOURCE_PLLCLK;
  RCC_ClkInitStruct.AHBCLKDivider = RCC_SYSCLK_DIV1;
  RCC_ClkInitStruct.APB1CLKDivider = RCC_HCLK_DIV4;  
  RCC_ClkInitStruct.APB2CLKDivider = RCC_HCLK_DIV2;  
  if(HAL_RCC_ClockConfig(&RCC_ClkInitStruct, FLASH_LATENCY_5) != HAL_OK)
  {
    /* Initialization Error */
    Error_Handler();
  }

  /* STM32F405x/407x/415x/417x Revision Z devices: prefetch is supported */
  if (HAL_GetREVID() == 0x1001)
  {
    /* Enable the Flash prefetch */
    __HAL_FLASH_PREFETCH_BUFFER_ENABLE();
  }
}

